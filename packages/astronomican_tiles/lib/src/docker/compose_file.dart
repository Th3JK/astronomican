import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import '../config/map_config.dart';
import '../tiles/planetiler.dart';

/// How containers run on this host.
final class HostSettings {
  /// Settings for this host.
  const HostSettings({this.user, this.selinux = false});

  /// `uid:gid` to run as, on Linux and macOS.
  final String? user;

  /// Whether bind mounts need SELinux relabelling.
  final bool selinux;
}

/// Writes the `docker-compose.yml` a map is built and previewed with.
///
/// Readable on purpose: it sits in the map's `.work` folder and can be run by
/// hand. Every path is absolute with forward slashes — `C:/…` works with
/// Docker Desktop — and every port is bound to 127.0.0.1 only.
///
/// | Service | Profile | What |
/// |---|---|---|
/// | planetiler | generate | OpenStreetMap → OpenMapTiles-schema `.mbtiles` |
/// | spreet | style | the OSM OpenMapTiles sprite from its SVG icons |
/// | tileserver | preview | TileServer GL serving the pack to a browser |
/// | maputnik | edit | the style editor, on the same tiles |
abstract final class ComposeFile {
  /// The compose project name of [config]'s map.
  static String project(MapConfig config) => 'astronomican-${config.id}';

  /// The compose file for [config], its work folder at [work] and the shared
  /// cache at [cache]. [spreetIcons], when given, adds the sprite builder.
  static String render({
    required MapConfig config,
    required Directory work,
    required Directory cache,
    required HostSettings host,
    Directory? spreetIcons,
  }) {
    final out = StringBuffer()
      ..writeln(
        '# Generated by astronomican_tiles from ${_posix(config.file.path)};',
      )
      ..writeln('# rewritten on every run. By hand, from this folder:')
      ..writeln(
        '#   docker compose run --rm planetiler                  # build the tiles',
      )
      ..writeln(
        '#   docker compose --profile preview up                 # http://localhost:${config.previewPort}',
      )
      ..writeln(
        '#   docker compose --profile preview --profile edit up  # + Maputnik on http://localhost:${config.editorPort}',
      )
      ..writeln('name: ${_q(project(config))}')
      ..writeln('services:');

    void volumes(List<(String, String, bool)> mounts) {
      out.writeln('    volumes:');
      for (final (source, target, readOnly) in mounts) {
        out
          ..writeln('      - type: bind')
          ..writeln('        source: ${_q(_posix(source))}')
          ..writeln('        target: ${_q(target)}');
        if (readOnly) out.writeln('        read_only: true');
        if (host.selinux) {
          out
            ..writeln('        bind:')
            ..writeln('          selinux: z');
        }
      }
    }

    void user() {
      if (host.user != null) out.writeln('    user: ${_q(host.user!)}');
    }

    // Planetiler.
    final input = config.input;
    if (input is! ExistingTilesInput) {
      out
        ..writeln('  planetiler:')
        ..writeln('    image: ${_q(config.images.planetiler)}')
        ..writeln('    profiles: ["generate"]');
      user();
      out
        ..writeln('    environment:')
        ..writeln('      JAVA_TOOL_OPTIONS: ${_q('-Xmx${config.memory}')}')
        ..writeln('      HOME: "/tmp"');
      volumes([
        (p.join(cache.path, 'planetiler', 'sources'), '/sources', false),
        (p.join(work.path, 'tiles'), '/output', false),
        if (input is OsmInput) (input.file.parent.path, '/osm', true),
      ]);
      out.writeln('    command: ${_list(Planetiler.arguments(config))}');
    }

    // spreet.
    if (spreetIcons != null) {
      out
        ..writeln('  spreet:')
        ..writeln('    image: ${_q(config.images.spreet)}')
        ..writeln('    profiles: ["style"]');
      user();
      volumes([
        (spreetIcons.path, '/icons', true),
        (p.join(work.path, 'style-src'), '/out', false),
      ]);
    }

    // TileServer GL.
    out
      ..writeln('  tileserver:')
      ..writeln('    image: ${_q(config.images.tileserver)}')
      ..writeln('    profiles: ["preview"]')
      ..writeln('    command: ["--config", "/data/config.json"]')
      ..writeln('    ports: [${_q('127.0.0.1:${config.previewPort}:8080')}]');
    volumes([
      (p.join(work.path, 'preview'), '/data', true),
      (p.join(work.path, 'pack'), '/pack', true),
    ]);

    // Maputnik.
    out
      ..writeln('  maputnik:')
      ..writeln('    image: ${_q(config.images.maputnik)}')
      ..writeln(
        '    # Published for amd64 only: Rosetta on Apple silicon, qemu on arm64 Linux.',
      )
      ..writeln('    platform: "linux/amd64"')
      ..writeln('    profiles: ["edit"]');
    user();
    out
      ..writeln(
        '    command: ["--file", "/styles/style.json", "--watch", "--no-browser"]',
      )
      ..writeln('    ports: [${_q('127.0.0.1:${config.editorPort}:8000')}]');
    volumes([(p.join(work.path, 'edit'), '/styles', false)]);
    return out.toString();
  }

  static String _posix(String path) => path.replaceAll(r'\', '/');

  /// A YAML scalar that means exactly [s]: JSON strings are valid YAML.
  static String _q(String s) => jsonEncode(s);

  static String _list(List<String> items) => '[${items.map(_q).join(', ')}]';
}
