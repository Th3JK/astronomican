import 'dart:typed_data';
import 'dart:ui' show Size;

import '../core/map_image.dart';
import '../core/map_level.dart';

/// A 1 × 1 transparent PNG: a picture that decodes, costs nothing and needs
/// no asset.
final Uint8List transparentPng = Uint8List.fromList(const [
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, //
  0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
  0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
  0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
  0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
]);

/// A level drawn with [transparentPng], for widget tests of maps that do not
/// care what the picture looks like.
MapLevel sampleLevel(
  String id, {
  String? label,
  Size size = const Size(2000, 1000),
}) => MapLevel(
  id: id,
  label: label ?? id,
  image: MapImage.memory(transparentPng),
  size: size,
);
